export function lookupVendor(mac) {
  if (!mac) return null;
  const clean = mac.replace(/[:\-.]/g, '').toUpperCase();
  if (clean.length < 6) return null;
  const prefix = clean.slice(0, 6);
  return OUI[prefix] || null;
}
